"""``docs/BENCHMARK_RESULTS.md``: the published results, generated from runs, never typed.

It is the Markdown report of the headline run with the verdict text verbatim, the supporting runs
after it, the spend, the limitations a reader needs and the commands that reproduce it. Nothing in
it is written by hand except the limitations, which are constants here so that a regenerated file
cannot lose them.
"""

from __future__ import annotations

import re
from collections import defaultdict
from datetime import UTC, datetime
from typing import Any

from fusion.bench.report.data import Report
from fusion.bench.report.fmt import money
from fusion.bench.report.markdown import render_markdown

__all__ = ["LIMITATIONS", "render_results", "spend_by_run"]

LIMITATIONS = """\
- **The tasks are synthetic.** An LLM drafted them and they were not reviewed by a person; see
  [evals/datasets/README.md](../evals/datasets/README.md#provenance-and-validity-read-this-before-quoting-a-number).
  They test whether an answer finds the seeded defect, names the root cause or passes the hidden
  tests, not how an answer feels in a real project.
- **It is a small study.** The $20 budget caps it at a few dozen tasks and a few repeats, so
  the intervals are wide and many verdicts are *inconclusive*. That is a result: the study could
  not tell, which is not the same as the arms being equal.
- **The scorers decide the numbers.** Review, debugging and rubric scores come from keyword and
  structure matching with a cheap LLM judge for what they cannot settle; no judge is from a
  different vendor than every arm (each vendor sits on a panel), so it may favour its own style.
  Frontend and performance scores are measured (tests, timings, accessibility), not judged by a
  model, and they check structure and speed, not intent or taste.
- **Prices and speeds are those of the day.** Costs use the catalog's prices (dates in the
  methodology); latencies depend on provider load at the time of the run.
- **One dataset, one set of models.** A different task mix, a newer model or another judge can
  change a verdict. The tuning used the `dev` split and this report is from the held-out `test`
  split, but both come from the same author and generator.
- **Claude Code is not in the loop.** Fusion's `digest` aggregation hands the merge to the
  calling model; in a study the panel's digest is scored as it is, with no model merging it.
"""

def _demote(markdown: str, levels: int) -> str:
    """The same Markdown with every heading ``levels`` deeper (the file has no code fences)."""
    return re.sub(
        r"^(#{1,5}) ", lambda m: "#" * (len(m.group(1)) + levels) + " ", markdown, flags=re.M
    )


def spend_by_run(entries: list[dict[str, Any]]) -> list[tuple[str, float]]:
    """Live spend per run. A study's entries are ``<run id> <arm> <task>``; anything else (a judge
    calibration, a dataset draft) is listed under its own ``task`` name."""
    totals: dict[str, float] = defaultdict(float)
    for entry in entries:
        purpose = str(entry.get("purpose", "")).split()
        name = purpose[0] if entry.get("task") == "bench" and purpose else str(entry.get("task"))
        totals[name] += float(entry.get("usd", 0.0))
    return sorted(totals.items())


def render_results(
    headline: Report,
    supporting: list[Report] | None = None,
    *,
    ledger: list[dict[str, Any]] | None = None,
    html_link: str | None = None,
    commands: list[str] | None = None,
    today: str | None = None,
) -> str:
    """The results document for ``headline`` and any ``supporting`` runs."""
    day = today or datetime.now(UTC).strftime("%Y-%m-%d")
    run = headline.run
    out = [
        "# Benchmark results",
        "",
        f"<!-- Generated by `fusion bench results {run.run_id}` on {day}. Do not edit by hand: "
        "rerun the command. -->",
        "",
        f"Generated on {day} from run `{run.run_id}`"
        + (" (**simulated: these are not measurements of real models**)" if run.mock else "")
        + ". The verdicts below are the verdict engine's text, unedited; how to read them is in "
        "[BENCHMARKING.md](BENCHMARKING.md#statistics-reports-and-how-to-read-them).",
        "",
    ]
    if html_link:
        out += [f"The full report with its charts is [{html_link}]({html_link}).", ""]
    out += [render_markdown(headline).split("\n", 1)[1].lstrip("\n"), ""]
    for report in supporting or []:
        out += [
            f"## Supporting study: {report.run.run_id}",
            "",
            f"Arms: {', '.join(a.arm for a in report.stats.arms)}. "
            f"Baseline for the comparisons: {report.stats.baseline}.",
            "",
            _demote(render_markdown(report).split("\n", 1)[1].lstrip("\n"), 1),
            "",
        ]
    if ledger is not None:
        rows = spend_by_run(ledger)
        out += ["## Spend", ""]
        out += ["| Run | Live spend |", "|---|---|"]
        out += [f"| {name} | {money(usd)} |" for name, usd in rows]
        out += [f"| **Total** | **{money(sum(u for _, u in rows))}** of the $20 cap |", ""]
    out += ["## Limitations", "", LIMITATIONS]
    cmds = commands or [
        f"uv run fusion bench report {run.run_id} --format html",
        f"uv run fusion bench results {run.run_id}",
    ]
    out += ["## Reproduce", "", "```bash", *cmds, "```", ""]
    return "\n".join(out)
